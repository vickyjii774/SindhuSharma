/* ---------------------------- Helpers ------------------------------- */

export const getCategoryBySlug = (slug) =>
  siteData.eventCategories.find((c) => c.slug === slug);

export const getEventsForCategory = (category) =>
  (category && siteData.events[category.key]) || [];

/** First event image in a category, used as a fallback card image. */
export const getCategoryImage = (category) =>
  category.image || getEventsForCategory(category).find((e) => e.image)?.image || "";

export const getEvent = (slug, id) => {
  const category = getCategoryBySlug(slug);
  const event = getEventsForCategory(category).find((e) => e.id === id);
  return { category, event };
};

export const getExperience = (id) =>
  siteData.experiences.find((e) => e.id === id);

/** Social links that actually have a URL. */
export const getActiveSocial = () =>
  Object.entries(siteData.personal.social).filter(([, url]) => Boolean(url));
